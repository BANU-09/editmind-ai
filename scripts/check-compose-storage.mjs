import assert from 'node:assert/strict';
import {createHash, randomUUID} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {mkdtemp, readFile, rm} from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {setTimeout as wait} from 'node:timers/promises';
import {GetObjectCommand, S3Client} from '@aws-sdk/client-s3';

// Run inside the app container so the check uses the private Compose S3 network.
const base = 'http://127.0.0.1:' + (process.env.PORT || '3000');
const headers = {'x-guest-id':randomUUID(), 'X-Correlation-Id':randomUUID()};
const dir = await mkdtemp(path.join(os.tmpdir(),'editmind-object-check-'));
const source = path.join(dir,'source.mp4');
const sha = bytes => createHash('sha256').update(bytes).digest('hex');
const sdk = new S3Client({region:process.env.S3_REGION,endpoint:process.env.S3_ENDPOINT,forcePathStyle:true});
async function json(method, route, body) {
  const result = await fetch(base + route, {
    method, headers:{...headers,'Content-Type':'application/json','Idempotency-Key':randomUUID()},
    body:body ? JSON.stringify(body) : undefined,
  });
  const data=await result.json();
  assert.ok(result.ok,JSON.stringify(data));
  return data;
}
async function finish(id) {
  for (let i=0;i<300;i++) {
    const job=await json('GET','/api/v1/jobs/'+id);
    if (job.status==='succeeded') return job;
    assert.notEqual(job.status,'failed',JSON.stringify(job.error));
    await wait(500);
  }
  throw new Error('Job polling timed out.');
}
async function fetchArtifact(url) {
  const response=await fetch(base+url,{headers});
  assert.equal(response.status,200);
  return Buffer.from(await response.arrayBuffer());
}
async function readIndependentObject(key) {
  const result=await sdk.send(new GetObjectCommand({Bucket:process.env.S3_BUCKET,Key:key}));
  return Buffer.from(await result.Body.transformToByteArray());
}
try {
  const ready=await json('GET','/ready');
  assert.equal(ready.storage,'s3');
  execFileSync('ffmpeg',['-nostdin','-v','error','-f','lavfi','-i','testsrc2=size=176x144:rate=12','-t','3','-c:v','libx264','-threads','1','-pix_fmt','yuv420p',source]);
  const bytes=await readFile(source);
  const form=new FormData();form.append('video',new Blob([bytes],{type:'video/mp4'}),'source.mp4');
  form.append('rights','FFmpeg test pattern generated by this verification.');form.append('ai_generated','false');
  const intake=await fetch(base+'/api/v1/media/ingest',{method:'POST',headers:{...headers,'Idempotency-Key':randomUUID()},body:form});
  assert.equal(intake.status,202);
  const input=await finish((await intake.json()).job_id);
  const session=await json('POST','/api/v1/projects/'+input.project_id+'/sessions',{});
  const step=await json('POST','/api/v1/sessions/'+session.session_id+'/steps',{say:'Cut the first 1 second'});
  assert.equal(step.status,'applied');
  const queued=await json('POST','/api/v1/sessions/'+session.session_id+'/render',{resolution:'480p',quality:'fast',rights:'Generated FFmpeg test fixture.',ai_generated:false});
  const job=await finish(queued.job_id);
  const prefix='results/'+job.job_id+'/';
  const [httpVideo,s3Video,httpManifest,s3Manifest]=await Promise.all([
    fetchArtifact(job.result_links.download),readIndependentObject(prefix+'edited.mp4'),
    fetchArtifact(job.result_links.manifest),readIndependentObject(prefix+'manifest.json'),
  ]);
  assert.deepEqual(httpVideo,s3Video);
  assert.deepEqual(JSON.parse(httpManifest),JSON.parse(s3Manifest));
  const manifest=JSON.parse(httpManifest);
  assert.equal(manifest.settings.storage,'s3');
  assert.match(httpVideo.subarray(0,48).toString('latin1'),/ftyp/);
  console.log(JSON.stringify({checked_at:new Date().toISOString(),result:'passed',storage:ready.storage,
    input:{kind:'generated silent video',seconds:3,sha256:sha(bytes),job_status:input.status},
    render:{job_status:job.status,duration_s:step.duration_s,bytes:httpVideo.length,http_sha256:sha(httpVideo),s3_sha256:sha(s3Video)},
    manifest:{api_equals_s3:true,sha256:sha(s3Manifest),storage:manifest.settings.storage},service_version:manifest.versions.service},null,2));
} finally {
  sdk.destroy();
  await rm(dir,{recursive:true,force:true});
}

